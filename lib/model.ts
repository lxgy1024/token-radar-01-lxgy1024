// Token Radar, model "radar-2": snapshot in, ranked board out.
//
// The board ranks pre-token protocols by an implied value that is derived
// from the snapshot itself, never from a hand-written list of names:
//
//   comp     = the category's live-token multiple: the median market-cap /
//              TVL of the snapshot's own live-token protocols in that
//              category (at least two of them), else the overall median
//              across all live protocols, clamped to [0.05, 1.0]
//   growth   = clamp(change_7d, -60, 120) per cent
//   implied  = round( tvl_usd x comp x (1 + growth/100 x 0.5)
//                     x maturity x chainMult )
//   maturity = 0.6 + min(age_days, 1095) / 1095 x 0.4   (unknown age: 365)
//   chainMult = 1 + 0.03 x min(chains - 1, 4)
//
// A protocol is pre-token when the snapshot records no token for it: no
// market cap, no CoinGecko id, no symbol. Saying it "records no token" is
// the claim; the snapshot cannot prove it has none. Live-token protocols
// are kept apart and shown with their market cap, never mixed into the
// ranking. Wrapped, staked and bridged products are left out of the early
// radar the same way the watchlist leaves them out: a wrapped or staked
// product of a token that already trades is not a launch that is still
// to come.

/** One protocol as the sealed snapshot carries it: exactly ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole sealed snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, printed on the dashboard next to the formula. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  comp_floor: number;
  comp_cap: number;
  chain_step: number;
  chain_max_extra: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  comp_floor: 0.05,
  comp_cap: 1.0,
  chain_step: 0.03,
  chain_max_extra: 4,
};

export const MODEL_VERSION = 'radar-2';

